        foreach (self::MACHINES as $name => $r) {
            $machines[] = [$name, $r['lanes'] === null ? '制限なし' : implode('→', $r['lanes']), (string) ($r['bed'] ?? ''), (string) ($r['moveTo'] ?? ''), implode('・', $r['words']), implode('・', [...self::NOT_MACHINE_WORDS, ...$r['except']]), self::MACHINE_NOTES[$name] ?? ''];
        }
        $rules = [['区分', 'ルール', '今の状態'], ...self::BOOKING_RULES];
        $sunday = [['日曜メニュー', '受付', '機器', '初診のレーン', '初診の時間（分）', '再診のレーン', '再診の時間（分）', 'ご来院前のお願い']];
        $s = TattooBooking::settings();
        $sunday[] = ['タトゥー除去・アートメイク除去', $s['enabled'] && ($s['tattooOn'] || $s['artmakeOn']) ? 'オン' : 'オフ', $s['machine'], $s['explainLaneId'] . '（説明10分）→' . $s['laneId'], '説明10分＋面積', $s['laneId'], '面積で決まる', ''];
