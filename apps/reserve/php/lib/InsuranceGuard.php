    /** 書かれた内容に合う案内の key（RULES の順）。insurance か acne に合えば maybe は出さない */
    public static function check(string $text): array
    {
        $text = normalize_width($text);
        $out = [];
        foreach (self::RULES as $key => $r) {
            $ok = $r['all'] !== [];
            foreach ($r['all'] as $p) {
                $ok = $ok && preg_match('/' . $p . '/u', $text) === 1;
            }
            foreach ($r['none'] as $p) {
                $ok = $ok && preg_match('/' . $p . '/u', $text) !== 1;
            }
            if ($ok) {
                $out[] = $key;
            }
        }
        if (array_intersect($out, ['insurance', 'acne']) !== []) {
            $out = array_values(array_diff($out, ['maybe']));
        }
        return $out;
    }

    /** 案内の文（key の順） */
    public static function texts(array $keys): array
    {
        return array_values(array_map(fn($k) => self::RULES[$k]['text'], array_filter($keys, fn($k) => isset(self::RULES[$k]))));
    }

    /** ページに渡す形（monshin/assets/insurance-guard.js が読む） */
    public static function forPage(): array
    {
        return array_map(fn($k, $r) => ['key' => $k, 'all' => $r['all'], 'none' => $r['none'], 'text' => $r['text']], array_keys(self::RULES), self::RULES);
    }
}
