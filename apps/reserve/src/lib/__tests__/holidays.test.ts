import { describe, expect, it } from "vitest";
import { holidayName, holidaysOf } from "@/lib/domain/holidays";

describe("祝日", () => {
  it("2026年の祝日（内閣府の発表と一致）", () => {
    const h = [...holidaysOf(2026).entries()].sort(([a], [b]) => a.localeCompare(b));
    expect(h).toEqual([
      ["2026-01-01", "元日"],
      ["2026-01-12", "成人の日"],
      ["2026-02-11", "建国記念の日"],
      ["2026-02-23", "天皇誕生日"],
      ["2026-03-20", "春分の日"],
      ["2026-04-29", "昭和の日"],
      ["2026-05-03", "憲法記念日"],
      ["2026-05-04", "みどりの日"],
      ["2026-05-05", "こどもの日"],
      ["2026-05-06", "振替休日"],
      ["2026-07-20", "海の日"],
      ["2026-08-11", "山の日"],
      ["2026-09-21", "敬老の日"],
      ["2026-09-22", "国民の休日"],
      ["2026-09-23", "秋分の日"],
      ["2026-10-12", "スポーツの日"],
      ["2026-11-03", "文化の日"],
      ["2026-11-23", "勤労感謝の日"],
    ]);
  });

  it("2027年の振替休日・春分・秋分", () => {
    expect(holidayName("2027-03-21")).toBe("春分の日");
    expect(holidayName("2027-03-22")).toBe("振替休日");
    expect(holidayName("2027-09-23")).toBe("秋分の日");
    expect(holidayName("2027-02-11")).toBe("建国記念の日");
    expect(holidayName("2027-10-11")).toBe("スポーツの日");
  });

  it("平日は undefined", () => {
    expect(holidayName("2026-10-07")).toBeUndefined();
  });
});
