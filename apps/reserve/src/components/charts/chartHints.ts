/** 施術名から、条件の欄に入れる項目の候補を出す（押すと「項目：」が入る） */
const RULES: [RegExp, string[]][] = [
  [/ハイフ|HIFU/i, ["カートリッジ", "深さ", "ショット数", "出力"]],
  [/脱毛|針/, ["出力", "パルス幅", "ショット数", "冷却"]],
  [/レーザー|シミ|ほくろ|色素|CO2|炭酸ガス|フラクショナル|ルビー|タイトニング|シャワー/i, ["出力（J/cm²）", "スポット径", "パルス幅", "ショット数"]],
  [/ボトックス|BTX|ヒアル|スネコス|ジュベ|リトゥオ|ジュブ|脂肪溶解|HARG|トラネ|注射|コラーゲン|フィル/i, ["希釈", "注入量", "注入点", "針"]],
  [/ピール|ピーリング|サリチル|ミラノ|TCA/i, ["濃度", "塗布時間", "層数"]],
  [/ダーマペン|ヴェル|ベル|サブシジョン/, ["針の深さ", "パス数", "併用薬剤"]],
];

export function conditionHints(treatment: string): string[] {
  const out: string[] = [];
  for (const [re, hints] of RULES) if (re.test(treatment)) out.push(...hints);
  return [...new Set(out)];
}
